#!/usr/bin/env python3
"""Build the static browser explorer using only Python's standard library.

Run ``python tools/build_site.py`` from the repository. The default output is
``dist/site``. Run ``bash serve.sh`` to build and serve in one command
(or ``bash serve.sh --python python`` to select that Python 3.10+ command).
The build downloads nothing. By default visitors load the pinned Pyodide
runtime from its CDN. Use --pyodide-dir to bundle a downloaded runtime, or
--pyodide-url to use another HTTPS or site-relative runtime location.
Use --check to verify an existing build without replacing it.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
from pathlib import Path, PurePosixPath
import posixpath
import re
import shutil
import sys
import tempfile
from urllib.parse import unquote, urlsplit
import zipfile

if __package__:
    from .check_version import check_version
else:
    from check_version import check_version


ROOT = Path(__file__).resolve().parents[1]
PYODIDE_VERSION = "314.0.7"
PYODIDE_URL = f"https://cdn.jsdelivr.net/pyodide/v{PYODIDE_VERSION}/full/"
PYODIDE_CORE_FILES = (
    "pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm",
    "python_stdlib.zip", "pyodide-lock.json",
)
MARKER = ".muql-site-build"
MARKER_TEXT = "Generated by MuQL Explorer tools/build_site.py\n"
# Only these repository-level documents and release evidence are public site
# inputs. Do not copy the repository or arbitrary report exports wholesale.
PUBLIC_FILES = (
    "README.md", "CONTRIBUTING.md", "SOURCES.md", "LICENSE",
    "docs/theories.html",
    "reports/tests.txt", "reports/browser-tests.txt", "reports/demo.txt",
    "reports/audit-benchmarks.json", "reports/audit-0.6.4-benchmarks.json",
)


def _destination(root: Path, output: Path) -> Path:
    """Never replace source files or an unrelated existing directory."""
    if output.is_symlink():
        raise ValueError("the output directory must not be a symbolic link")
    output = output.resolve()
    if output == root or output in root.parents:
        raise ValueError("the output directory must not contain the source repository")
    if (root in output.parents and output != root / "site"
            and (root / "dist") not in output.parents):
        raise ValueError("build output inside the repository must be site/ or below dist/")
    if output.exists():
        if not output.is_dir():
            raise ValueError("the output path is an existing file")
        if any(output.iterdir()):
            marker = output / MARKER
            if marker.is_symlink() or not marker.is_file() or marker.read_text(encoding="utf-8") != MARKER_TEXT:
                raise ValueError("refusing to replace a nonempty directory that is not a MuQL site build")
    return output


def _runtime_url(value: str | None) -> str:
    """Accept portable runtime directory URLs, never executable URL schemes."""
    if value is None:
        return PYODIDE_URL
    if (not isinstance(value, str) or not value
            or any(character.isspace() or ord(character) < 32 for character in value)
            or any(character in value for character in "\\?#")
            or re.search(r"%(?![0-9a-fA-F]{2})", value)):
        raise ValueError("the Pyodide URL must be an HTTPS or safe relative directory URL without credentials, query, or fragment")
    url = urlsplit(value)
    # Parsing the port also rejects malformed HTTPS authorities.
    if url.scheme:
        if (url.scheme != "https" or not url.hostname or url.username is not None
                or url.password is not None):
            raise ValueError("the Pyodide URL must use HTTPS without credentials")
        _ = url.port
    elif url.netloc or url.path.startswith("/"):
        raise ValueError("the Pyodide URL must be HTTPS or relative to the site")
    decoded = unquote(url.path)
    if ("\\" in decoded or any(character.isspace() or ord(character) < 32 for character in decoded)
            or ".." in PurePosixPath(decoded).parts
            or (not url.scheme and (not decoded or decoded.startswith("/")))):
        raise ValueError("the Pyodide URL must name a safe runtime directory")
    return url._replace(path=url.path.rstrip("/") + "/").geturl()


def _runtime_files(directory: str | Path | None, output: Path) -> tuple[Path | None, list[Path]]:
    if directory is None:
        return None, []
    source = Path(directory).absolute()
    if any(part.is_symlink() for part in (source, *source.parents)):
        raise ValueError("the Pyodide runtime directory must not use symbolic links")
    source = source.resolve()
    if not source.is_dir():
        raise ValueError("the Pyodide runtime directory does not exist")
    if source == output or source in output.parents or output in source.parents:
        raise ValueError("the Pyodide runtime and site output must not overlap")
    files = list(_files(source))
    for name in PYODIDE_CORE_FILES:
        path = source / name
        if not path.is_file() or path.stat().st_size == 0:
            raise ValueError(f"the Pyodide runtime is missing a nonempty core file: {name}")
    try:
        lock = json.loads((source / "pyodide-lock.json").read_text(encoding="utf-8"))
        version = lock.get("info", {}).get("version") if isinstance(lock, dict) else None
    except (UnicodeError, ValueError, AttributeError) as error:
        raise ValueError("the Pyodide runtime lockfile is invalid") from error
    if version != PYODIDE_VERSION:
        raise ValueError(f"the Pyodide runtime must be version {PYODIDE_VERSION}; lockfile reports {version!r}")
    return source, files


def _digest(path: Path) -> bytes:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.digest()


def _compare_site(expected: Path, actual: Path) -> None:
    def manifest(directory):
        result = {}
        for path in directory.rglob("*"):
            if path.is_symlink():
                raise ValueError(f"site output must not contain symbolic links: {path}")
            if path.is_file():
                result[path.relative_to(directory).as_posix()] = _digest(path)
        return result
    wanted, existing = manifest(expected), manifest(actual)
    differences = sorted(name for name in wanted.keys() | existing.keys()
                         if wanted.get(name) != existing.get(name))
    if differences:
        sample = ", ".join(differences[:8])
        if len(differences) > 8:
            sample += f", and {len(differences) - 8} more"
        raise ValueError("site output differs from a fresh build: " + sample)


def _files(directory: Path):
    for path in sorted(directory.iterdir()):
        # Dotfiles and their trees are private build inputs, never public assets.
        # The two required site markers are generated explicitly below.
        if path.name.startswith(".") or path.name == "__pycache__":
            continue
        if path.is_symlink():
            raise ValueError(f"site inputs must not contain symbolic links: {path}")
        if path.is_dir():
            yield from _files(path)
        elif path.is_file() and path.suffix not in {".pyc", ".pyo"}:
            yield path


def _public_file(root: Path, name: str) -> Path:
    """Validate every component of an explicitly published source path."""
    source = root
    for part in PurePosixPath(name).parts:
        source = source / part
        if source.is_symlink():
            raise ValueError(f"site inputs must not contain symbolic links: {source}")
    if not source.is_file():
        raise ValueError(f"public site input is missing: {name}")
    return source


def _examples(root: Path) -> list[dict]:
    examples = json.loads((root / "web" / "examples.json").read_text(encoding="utf-8"))
    if not isinstance(examples, list) or not examples:
        raise ValueError("web/examples.json must contain a nonempty array of examples")
    seen = set()
    for entry in examples:
        if not isinstance(entry, dict) or not isinstance(entry.get("id"), str) or not entry["id"]:
            raise ValueError("each browser example must have a nonempty string id")
        if entry["id"] in seen:
            raise ValueError(f"duplicate browser example id: {entry['id']}")
        seen.add(entry["id"])
        name = entry.get("file")
        if not isinstance(name, str):
            raise ValueError(f"example {entry['id']} needs a theory file")
        path = PurePosixPath(name)
        if (path.is_absolute() or ".." in path.parts or "\\" in name
                or not path.parts or path.parts[0] != "examples" or path.suffix != ".md"
                or any(part.startswith(".") for part in path.parts)):
            raise ValueError(f"example {entry['id']} must refer to a Markdown file below examples/")
        source = root.joinpath(*path.parts)
        if not source.is_file() or source.is_symlink() or (root / "examples") not in source.resolve().parents:
            raise ValueError(f"missing or unsafe example theory: {name}")
        if entry.get("mode") not in ("check", "search"):
            raise ValueError(f"example {entry['id']} needs mode check or search")
    for entry in examples:
        next_example = entry.get("next")
        if next_example is not None and (not isinstance(next_example, str) or next_example not in seen):
            raise ValueError(f"example {entry['id']} refers to an unknown next example")
    return examples


def _relocate_guide(text: str) -> str:
    """Keep the generated reader's docs-relative links valid at the site root."""
    def link(match):
        quote, target = match.groups()
        url = urlsplit(html.unescape(target))
        if url.scheme or url.netloc or not url.path or url.path.startswith("/"):
            return match.group(0)
        path = posixpath.normpath(posixpath.join("docs", url.path))
        return "href=" + quote + html.escape(url._replace(path=path).geturl(), quote=True) + quote
    return re.sub(r"\bhref=([\"'])([^\"']*)\1", link, text)


def build(output: str | Path | None = None, *, root: Path = ROOT,
          pyodide_url: str | None = None, pyodide_dir: str | Path | None = None,
          check: bool = False) -> Path:
    root = root.resolve()
    output = _destination(root, Path(output) if output is not None else root / "dist" / "site")
    if pyodide_url is not None and pyodide_dir is not None:
        raise ValueError("choose either a Pyodide URL or a bundled Pyodide directory")
    runtime_url = _runtime_url(pyodide_url)
    runtime_source, runtime_files = _runtime_files(pyodide_dir, output)
    if runtime_source is not None:
        runtime_url = "runtime/pyodide/"
    if check and not output.is_dir():
        raise ValueError("the site output does not exist; build it before using --check")
    # Validate source roots as well as their descendants before reading inputs.
    for name in ("web", "examples", "docs", "muql", "reports"):
        if (root / name).is_symlink():
            raise ValueError(f"site inputs must not contain symbolic links: {root / name}")
    version = check_version(root)
    examples = _examples(root)
    static_files = list(_files(root / "web"))
    if not (root / "web" / "index.html").is_file():
        raise ValueError("web/index.html is missing")
    modules = sorted(path for path in (root / "muql").glob("*.py")
                     if not path.name.startswith("."))
    if not (root / "muql" / "web.py").is_file():
        raise ValueError("the browser bridge muql/web.py is missing")
    if any(path.is_symlink() for path in modules):
        raise ValueError("Python engine files must not be symbolic links")
    theory_files = list(_files(root / "examples"))
    documentation = [source for source in _files(root / "docs") if source.suffix == ".md"]
    public_files = [_public_file(root, name) for name in PUBLIC_FILES]
    guide = root / "docs" / "theories.html"

    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".muql-site-", dir=output.parent) as temporary:
        staging = Path(temporary) / "site"
        staging.mkdir()
        for source in static_files:
            target = staging / source.relative_to(root / "web")
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
        if runtime_source is not None:
            runtime_target = staging / "runtime" / "pyodide"
            if runtime_target.exists():
                raise ValueError("web/runtime/pyodide is reserved for the bundled runtime")
            for source in runtime_files:
                target = runtime_target / source.relative_to(runtime_source)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
        for source in theory_files:
            if source.suffix == ".md":
                target = staging / source.relative_to(root)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
        for source in [*documentation, *public_files]:
            target = staging / source.relative_to(root)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
        (staging / "theories.html").write_text(_relocate_guide(guide.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
        shutil.copyfile(root / "LICENSE", staging / "LICENSE.txt")
        with zipfile.ZipFile(staging / "engine.zip", "w", compression=zipfile.ZIP_DEFLATED) as engine:
            for source in [*modules, root / "LICENSE"]:
                item = zipfile.ZipInfo(source.relative_to(root).as_posix(), date_time=(1980, 1, 1, 0, 0, 0))
                item.create_system = 3
                item.compress_type = zipfile.ZIP_DEFLATED
                item.external_attr = 0o100644 << 16
                engine.writestr(item, source.read_bytes())
        config = {"version": version, "engine": "engine.zip", "examples": "examples.json", "pyodide": runtime_url}
        (staging / "config.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8", newline="\n")
        (staging / MARKER).write_text(MARKER_TEXT, encoding="utf-8", newline="\n")
        (staging / ".nojekyll").touch()
        # Recheck before replacement, after all inputs have been read successfully.
        _destination(root, output)
        if check:
            _compare_site(staging, output)
        else:
            if output.exists():
                shutil.rmtree(output)
            staging.rename(output)
    print(f"{'Verified' if check else 'Built'} 3μQL Explorer {version}: {output}")
    print(f"Included {len(examples)} example presets and {len(modules)} Python engine modules.")
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, help="output directory (default: repository dist/site)")
    runtime = parser.add_mutually_exclusive_group()
    runtime.add_argument("--pyodide-url", help="HTTPS or site-relative runtime directory (default: pinned jsDelivr CDN)")
    runtime.add_argument("--pyodide-dir", type=Path, help=f"bundle a local Pyodide {PYODIDE_VERSION} runtime directory, including any supplied packages")
    parser.add_argument("--check", action="store_true", help="compare output with a fresh build without modifying it; use the same runtime options as the original build")
    args = parser.parse_args()
    try:
        build(args.output, pyodide_url=args.pyodide_url,
              pyodide_dir=args.pyodide_dir, check=args.check)
    except (OSError, ValueError, SyntaxError) as error:
        print(f"Site build failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
